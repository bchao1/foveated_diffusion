#!/usr/bin/env python
"""Rebuild the supplementary baseline figures with the two new baseline columns.

The published `paper_figures/supp/baseline_{1,2,3,101}.png` are 3-column tiles
(`high_res | naive | ours`). This adds the ToMe-2x2 and RALU-foveated columns generated by
`new_baselines_inference.py`, giving 5-column tiles:

    Full resolution | Token merging | RALU | Naive mixed-res. | Ours

Tile identity and order are taken from `baseline_figure_tiles.json`, recovered by
pixel-matching the published PNGs, because `make_supp_figures.py` shuffles with an unseeded
`np.random.shuffle`. So each new figure holds exactly the same examples, in the same order,
as the one it supersedes.

Layout: `baseline_1..3` go from 9 rows x 2 cols to **18 rows x 1 col** (5 columns no longer
fit two tiles across a page); `baseline_101` stays 4 rows x 1 col. Per-image pixel size is
unchanged from the published figures at the default downsample factors.

Writes to NEW filenames — nothing existing is overwritten.

    python make_baseline_figures_5col.py                  # all four figures + tiles
    python make_baseline_figures_5col.py --figures 101    # just the hero figure
    python make_baseline_figures_5col.py --no_tiles       # skip the full-res tile pass
"""

import argparse
import json
import os

import numpy as np
from PIL import Image, ImageDraw, ImageFont

from generate_paper_figures import _downsample_by_factor

EVAL_DIR = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(EVAL_DIR, "../results/eccv2026_final_v2")
FIGURES = os.path.join(EVAL_DIR, "../paper_figures/supp")
TILES_JSON = os.path.join(EVAL_DIR, "baseline_figure_tiles.json")

FONT_CANDIDATES = [
    "/home/brianchc/fonts/cmu-serif/cmunbx.ttf",          # CMU Serif Bold
    "/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf",
]

# (filename, which result tree, column label). "extra" is where the new arms landed.
COLUMNS = [
    ("img_high_res.png", "base",  "Full resolution"),
    ("img_tome.png",     "extra", "Token merging"),
    ("img_ralu.png",     "extra", "RALU"),
    ("img_naive.png",    "base",  "Naive mixed-res."),
    ("img_ours.png",     "base",  "Ours"),
]

# downsample factor per figure, matching the published versions so per-image pixel size
# does not change.
FIGURE_DOWNSAMPLE = {"1": 4, "2": 4, "3": 4, "101": 1}
FIGURE_ROWS = {"1": 18, "2": 18, "3": 18, "101": 4}


def tile_paths(prompt_set, image_id):
    base = os.path.join(RESULTS, f"baseline_comparison_randomized_{prompt_set}")
    extra = f"{base}_extra"
    out = []
    for fname, tree, _ in COLUMNS:
        root = base if tree == "base" else extra
        out.append(os.path.join(root, f"{image_id:05d}", fname))
    return out


def load_font(px):
    for path in FONT_CANDIDATES:
        if os.path.isfile(path):
            return ImageFont.truetype(path, px)
    print("WARNING: no serif TTF found, falling back to PIL's bitmap font")
    return ImageFont.load_default()


def hstack(images, pad):
    """Horizontal stack on a white background; images must share a height."""
    h = max(im.shape[0] for im in images)
    parts = []
    for k, im in enumerate(images):
        if k:
            parts.append(np.full((h, pad, im.shape[2]), 255, dtype=im.dtype))
        parts.append(im)
    return np.concatenate(parts, axis=1)


def vstack(rows, pad):
    w = max(r.shape[1] for r in rows)
    parts = []
    for k, r in enumerate(rows):
        if k:
            parts.append(np.full((pad, w, r.shape[2]), 255, dtype=r.dtype))
        parts.append(r)
    return np.concatenate(parts, axis=0)


def header_band(col_width, pad, n_cols, font_frac, pad_below):
    """A white band with one label centered over each column."""
    font_px = max(10, int(font_frac * col_width))
    font = load_font(font_px)
    height = int(font_px * 1.35) + pad_below
    width = n_cols * col_width + (n_cols - 1) * pad
    band = Image.new("RGB", (width, height), (255, 255, 255))
    draw = ImageDraw.Draw(band)
    for i, (_, _, label) in enumerate(COLUMNS):
        x0 = i * (col_width + pad)
        bbox = draw.textbbox((0, 0), label, font=font)
        tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
        draw.text((x0 + (col_width - tw) / 2 - bbox[0],
                   (height - pad_below - th) / 2 - bbox[1]),
                  label, font=font, fill=(0, 0, 0))
    return np.asarray(band)


def build_figure(name, tiles, downsample, pad_px, font_frac, out_path):
    pad = max(1, pad_px // downsample)
    rows = []
    for prompt_set, image_id in tiles:
        imgs = []
        for p in tile_paths(prompt_set, image_id):
            if not os.path.isfile(p):
                raise FileNotFoundError(p)
            a = np.asarray(Image.open(p).convert("RGB"))
            imgs.append(_downsample_by_factor(a, downsample))
        rows.append(hstack(imgs, pad))
    col_width = rows[0].shape[1] // len(COLUMNS)  # after padding this is approximate;
    col_width = (rows[0].shape[1] - (len(COLUMNS) - 1) * pad) // len(COLUMNS)
    band = header_band(col_width, pad, len(COLUMNS), font_frac, pad_below=pad)
    fig = vstack([band] + rows, pad)
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    Image.fromarray(fig).save(out_path)
    print(f"{os.path.basename(out_path)}: {len(rows)} rows x {len(COLUMNS)} cols, "
          f"{fig.shape[1]}x{fig.shape[0]}, downsample {downsample}, "
          f"{os.path.getsize(out_path) / 1e6:.1f} MB")


def build_full_res_tiles(tiles_by_figure, pad_px):
    """Full-resolution 5-column tiles, mirroring the existing `stacked/` convention so tiles
    can be re-picked later without rerunning this script's figure pass."""
    seen = set()
    for tiles in tiles_by_figure.values():
        for prompt_set, image_id in tiles:
            if (prompt_set, image_id) in seen:
                continue
            seen.add((prompt_set, image_id))
            out_dir = os.path.join(
                RESULTS, f"baseline_comparison_randomized_{prompt_set}_5col")
            os.makedirs(out_dir, exist_ok=True)
            imgs = [np.asarray(Image.open(p).convert("RGB"))
                    for p in tile_paths(prompt_set, image_id)]
            Image.fromarray(hstack(imgs, pad_px)).save(
                os.path.join(out_dir, f"{image_id:05d}.png"))
    print(f"wrote {len(seen)} full-res 5-column tiles to "
          f"{RESULTS}/baseline_comparison_randomized_*_5col/")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--figures", nargs="+", default=["1", "2", "3", "101"])
    ap.add_argument("--pad_px", type=int, default=20,
                    help="padding at full resolution; scaled by 1/downsample like "
                         "generate_paper_figures.py stack does")
    ap.add_argument("--font_frac", type=float, default=0.075,
                    help="label size as a fraction of one column's width")
    ap.add_argument("--suffix", type=str, default="_5col",
                    help="appended to the output filename so nothing is overwritten")
    ap.add_argument("--downsample", type=int, default=None,
                    help="override the per-figure default")
    ap.add_argument("--no_tiles", action="store_true",
                    help="skip writing the full-res 5-column tiles")
    args = ap.parse_args()

    with open(TILES_JSON) as f:
        raw = json.load(f)
    tiles_by_figure = {k: [tuple(t) for t in v] for k, v in raw.items()
                       if not k.startswith("_")}

    for name in args.figures:
        tiles = tiles_by_figure[name]
        assert len(tiles) == FIGURE_ROWS[name], \
            f"figure {name}: {len(tiles)} tiles but expected {FIGURE_ROWS[name]}"
        ds = args.downsample or FIGURE_DOWNSAMPLE[name]
        build_figure(name, tiles, ds, args.pad_px, args.font_frac,
                     os.path.join(FIGURES, f"baseline_{name}{args.suffix}.png"))

    if not args.no_tiles:
        build_full_res_tiles({k: tiles_by_figure[k] for k in args.figures}, args.pad_px)


if __name__ == "__main__":
    main()
